def get_material(t, start, end=None):
    i = t.find(start)
    if i < 0:
        return ""
    j = t.find(end, i + 1) if end else len(t)
    if j < 0:
        j = len(t)
    return t[i:j].strip()

def clean(s):
    lines = [l for l in s.split("\n") if not re.fullmatch(r"\d+", l.strip())]
    return "\n".join(lines).strip()

