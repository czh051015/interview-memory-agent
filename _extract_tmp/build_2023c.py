def get_material(t, start, end=None):
    i = t.find(start)
    if i < 0:
        return ""
    j = t.find(end, i + 1) if end else len(t)
    if j < 0:
        j = len(t)
    return t[i:j].strip()

def clean(s):
    out = []
    for l in s.split("\n"):
        ls = l.strip()
        if re.fullmatch(r"\d+", ls):
            continue
        if re.fullmatch(r"\d+\s*/\s*\d+", ls):   # page number like " 1 / 12 "
            continue
        if "免费获取" in ls or "hijoeyyy" in ls:  # ad watermark
            continue
        out.append(l)
    return "\n".join(out).strip()

