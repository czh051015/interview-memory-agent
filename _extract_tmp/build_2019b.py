def get_material(t, start, end=None):
    i = t.find(start)
    if i < 0:
        return ""
    j = t.find(end, i + 1) if end else len(t)
    if j < 0:
        j = len(t)
    return t[i:j].strip()

def clean(s):
    out = []
    for l in s.split("\n"):
        ls = l.strip()
        if re.fullmatch(r"\d+", ls):
            continue
        if re.fullmatch(r"-\s*\d+\s*-", ls):   # page marker like "- 3 -"
            continue
        out.append(l)
    return "\n".join(out).strip()

