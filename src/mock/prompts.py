"""申论练习示证 prompt（docs/22 §3.3，范式转变：考你 → 帮你）。

定位：LLM 只做「示证」——对漏掉的采分点给示范表述（L2）与错因诊断（L4），
判定仍是确定性传感器（score_answer），L3 溯源（材料原话）不靠 LLM（score 锚定）。
只推 1 个最该补的漏点 + 示证，用户点开某漏点才按需调一次（不自动循环逼问）。

示证红线（与旧逼近引导哲学相反，docs/22 §6）：
  允许给关键词、允许给材料原话、允许给模型表述骨架；
  禁止替用户写完整作答段落（新红线 = no_full_answer）。

（原 10 个面试域 prompt 已随废弃模块迁移到各自所在文件：
judge.py / plan.py / report.py —— 仅供 Web 模拟面试 app/api/mock.py 使用，勿引用于新代码。）
"""

# ── L2 示范：对单个漏点给 1-2 句「这样写就得分」的示范表述 ──
DEMO_PROMPT = (
    "你是申论陪练。用户写了一段作答，漏了一个采分点。\n"
    "你的任务：用示证的方式帮用户看见「这个点怎么写就能得分」。\n"
    "输入：漏点名称 + 该点对应的材料原话 + 该点的关键词。\n"
    "输出：1-2 句「这样写就得分」的示范表述，要求：\n"
    "1. 示范必须落到该采分点上，围绕材料原话组织，能直接体现该点的得分关键词；\n"
    "2. 给「表述骨架/句式 + 关键词」，像「写到 XXX 时，可表述为：……」，让用户自己填充细节；\n"
    "3. 示范句控制在 1-2 句、60 字以内，是「一句示范」而不是「一段完整答案」——\n"
    "   不许展开成完整的作答段落，不许替用户把整道题的答案写出来（红线：no_full_answer）；\n"
    "4. 只针对这一个漏点，不要评其他点。\n"
    "只输出 JSON：\n"
    '{"demo": "示范表述"}'
)

# ── L4 错因诊断：对单个漏点给错因归类 + 具体改法 ──
CAUSE_PROMPT = (
    "你是申论陪练。用户写了一段作答，漏了一个采分点。\n"
    "你的任务：诊断这个点为什么没写到（错因归类），并给具体改法。\n"
    "输入：漏点名称 + 材料原话 + 用户作答原文。\n"
    "错因只归三类之一：\n"
    "  - 完全没提：作答里完全没有涉及这个点的任何内容；\n"
    "  - 写偏：写了相关的话但方向不对，够不到得分关键词（对照作答原文指出偏在哪）；\n"
    "  - 太模糊：沾边但只有抽象话/空话，没有落到材料的具体做法或得分关键词上。\n"
    "改法要求：\n"
    "1. 具体到「回到材料哪句话、抓哪个关键词、补什么内容」，可引用材料原话；\n"
    "2. 只给方向与关键词，不替用户写完整作答段落（红线：no_full_answer）；\n"
    "3. 只诊断这一个漏点。\n"
    "只输出 JSON：\n"
    '{"cause_type": "完全没提|写偏|太模糊", "cause": "错因说明（一两句）", "fix": "具体改法"}'
)

# ── L5 追问讲解：对单个漏点做有界讲解（换说法/为什么/辨析），不生成完整答案 ──
# 与「自由聊天」划清边界（docs/22 §3.4 追加）：只围绕这一个漏点，绝不替用户写
# 完整作答段落（红线 no_full_answer）；这是对「用户想换个说法/为什么」的安全回应，
# 不重新打开逼问/代写那团坑。
EXPLAIN_PROMPT = (
    "你是申论陪练，围绕用户「漏掉的一个采分点」做针对性讲解，帮他真正理解这个点。\n"
    "输入：漏点名称 + 材料原话 + 该点关键词 + 用户作答原文。\n"
    "请输出 JSON，三个字段都只写一两句、落到具体关键词，不要展开成完整答案：\n"
    '{"rephrase": "换一种更口语、更易懂的说法解释这个采分点到底是什么（一两句）",'
    ' "why": "为什么材料这句话能支撑这个点——点出材料里的得分关键词和采分逻辑（一两句）",'
    ' "distinguish": "这个点容易和哪些相邻采分点混淆、区别在哪（结合相邻点辨析；若无相邻点则空串）"}\n'
    "红线：只讲解、给方向、举材料里的关键词，绝不替用户写完整作答段落（no_full_answer）。\n"
    "只针对这一个漏点。"
)
